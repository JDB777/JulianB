/**
 * Copy the DM's rulebook into the app.
 *
 *   node scripts/build-rulebook.mjs
 *
 * The source is .claude/DnD/dm/SYSTEM-PROMPT.generated.md, itself assembled
 * from rules/ and dm/ by build_system_prompt.py. It becomes a JS module so the
 * serverless function bundles it with no file reads at runtime. Rebuild after
 * the rules change, then deploy. It sits in front of the cache breakpoint, so
 * it should change only when the rules do.
 */

import fs from 'fs';

const SRC = 'C:/Users/Julia/.claude/DnD/dm/SYSTEM-PROMPT.generated.md';
const OUT = new URL('../api/_lib/rulebook.js', import.meta.url);

const text = fs.readFileSync(SRC, 'utf8');
fs.writeFileSync(OUT,
  '/* GENERATED by scripts/build-rulebook.mjs from SYSTEM-PROMPT.generated.md. Do not edit by hand.\n'
  + ' *\n'
  + ' * This work includes material from the System Reference Document 5.2 ("SRD 5.2")\n'
  + ' * by Wizards of the Coast LLC, available at https://www.dndbeyond.com/srd.\n'
  + ' * The SRD 5.2 is licensed under the Creative Commons Attribution 4.0\n'
  + ' * International License, available at\n'
  + ' * https://creativecommons.org/licenses/by/4.0/legalcode. */\n\n'
  + `export const RULEBOOK = ${JSON.stringify(text)};\n`);

console.log(`rulebook.js: ${text.length.toLocaleString()} characters, `
          + `~${Math.round(text.split(/\s+/).length * 1.4 / 1000)}k tokens`);
